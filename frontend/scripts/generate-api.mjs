import { execFileSync } from 'node:child_process';
import { log } from 'node:console';
import { readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = fileURLToPath(new URL('../../', import.meta.url));
const python =
  process.env.PROOFLINE_PYTHON ??
  (process.platform === 'win32' ? `${root}.venv/Scripts/python.exe` : `${root}.venv/bin/python`);
const schema = JSON.parse(
  execFileSync(python, ['scripts/export_openapi.py'], {
    cwd: root,
    encoding: 'utf8',
  }),
);
const generated = astToString(await openapiTS(schema));
const header = '// Generated by npm run generate:api. Do not edit by hand.\n';
const names = [
  'ActivateProposal',
  'AnalysisInput',
  'AssemblyOutput',
  'CaseCreate',
  'CaseDetail',
  'CasePage',
  'CasePatch',
  'CaseStatus',
  'CaseSummary',
  'DecisionCreate',
  'DecisionView',
  'EventTime',
  'EventType',
  'Evidence',
  'Fact',
  'FactKey',
  'FactValue',
  'FollowUp',
  'FollowUpAction',
  'IssueView',
  'JsonValue',
  'Money',
  'ProposalView',
  'Readiness',
  'ReplayOption',
  'RequirementKey',
  'RevisionCreate',
  'RunCreate',
  'RunView',
  'SnapshotSource',
  'SourceCreate',
  'SourceKind',
  'SourcePatch',
  'SourceVersionCreate',
  'SourceVersionSummary',
  'SourceVersionView',
  'SourceView',
  'SpanView',
  'TimeRole',
  'TimelineEvent',
  'ValidationView',
  'VersionCommand',
];
const aliases = names
  .map((name) => `export type ${name} = components['schemas']['${name}'];`)
  .join('\n');
const output = `${header}${generated}\n${aliases}\nexport type Capabilities = components['schemas']['Capabilities'];\n`;
const path = new URL('../src/api-types.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await readFile(path, 'utf8')) !== output) {
    throw new Error('API types are stale. Run npm run generate:api from frontend/.');
  }
  log('API types match the HTTP schema.');
} else {
  await writeFile(path, output);
  log('Generated frontend/src/api-types.ts.');
}
